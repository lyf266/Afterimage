#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Markdown Report Generator for Afterimage
Combines raw quantitative telemetry charts and AI cognitive retrospectives
into structured daily Markdown artifacts.
"""

from pathlib import Path
from typing import Any, Dict, Optional


class MarkdownReportGenerator:
    def __init__(self, output_dir: Path):
        self.output_dir = Path(output_dir).expanduser()
        self.output_dir.mkdir(parents=True, exist_ok=True)

    def generate_report(
        self,
        date_str: str,
        metrics: Dict[str, Any],
        ai_retrospective: Optional[str] = None,
    ) -> Path:
        report_file = self.output_dir / f"{date_str}.md"

        lines = [
            f"# Afterimage Cognitive Daily Retrospective: {date_str}",
            "",
            "> 🧠 Generated by **Afterimage Telemetry & Cognitive AI Engine**",
            "",
            "## 📊 Quantitative Telemetry Dashboard",
            "",
            f"- **Tracked Total**: {metrics.get('total_duration', '0m')}",
            f"- **Active Focus Time**: {metrics.get('active_duration', '0m')}",
            f"- **Focus Switches**: {metrics.get('switch_count', 0)} times",
            f"- **Typing Volume**: {metrics.get('total_keystrokes', 0):,} keystrokes (Avg: {metrics.get('avg_kpm', 0.0):.1f} KPM)",
            f"- **Mouse Vector**: {metrics.get('mouse_distance', '0 m')}",
            "",
            "### Category Distribution",
            "",
            "| Category | Duration | Percentage |",
            "| :--- | :--- | :--- |",
        ]

        for cat, dur, pct in metrics.get("categories", []):
            lines.append(f"| {cat} | {dur} | {pct:.1f}% |")

        lines.extend([
            "",
            "### Top Focus Applications",
            "",
            "| Application | Duration | Percentage |",
            "| :--- | :--- | :--- |",
        ])

        for app, dur, pct in metrics.get("top_apps", []):
            lines.append(f"| {app} | {dur} | {pct:.1f}% |")

        if ai_retrospective:
            lines.extend([
                "",
                "---",
                "",
                "## 🤖 AI Cognitive Retrospective & Synthesis",
                "",
                ai_retrospective.strip(),
                "",
            ])

        content = "\n".join(lines)
        report_file.write_text(content, encoding="utf-8")
        return report_file
